// =====================================================================
// Category.cs - مدل مربوط به دسته‌بندی محصولات
// =====================================================================
// این کلاس نمایانگر یک دسته‌بندی (مثلاً "ورزش‌های آبی"، "فوتبال") است.
// در Entity Framework Core، هر کلاس مدل معمولاً به یک جدول در پایگاه داده
// نگاشت (Map) می‌شود. نام جدول به صورت پیش‌فرض برابر نام کلاس است.
// =====================================================================

// تعریف namespace مربوط به مدل‌های پروژه
namespace WebApp.Models {
    // تعریف کلاس Category (دسته‌بندی)
    // این کلاس یک POCO (Plain Old CLR Object) است؛ یعنی فقط شامل ویژگی‌هاست
    public class Category {

        // کلید اصلی (Primary Key) جدول Category
        // در EF Core، ویژگی‌هایی با نام "Id" یا "CategoryId" به طور خودکار کلید اصلی در نظر گرفته می‌شوند
        // نوع long به این معنی است که این فیلد می‌تواند مقادیر بزرگی (بیش از 2 میلیارد) داشته باشد
        public long CategoryId { get; set; }

        // نام دسته‌بندی (مثلاً "Watersports")
        // string.Empty یعنی مقدار پیش‌فرض رشته خالی است (به جای null)
        // این کار کمک می‌کند تا از خطاهای NullReferenceException جلوگیری شود
        public string Name { get; set; } = string.Empty;

        // رابطه‌ی یک-به-چند با کلاس Product
        // یک دسته‌بندی می‌تواند چندین محصول داشته باشد
        // نوع IEnumerable<Product>? یعنی این ویژگی اختیاری است (می‌تواند null باشد)
        // معمولاً برای "navigation property" استفاده می‌شود تا بتوان از یک دسته به محصولاتش دسترسی داشت
        public IEnumerable<Product>? Products { get; set; }
    }
}
