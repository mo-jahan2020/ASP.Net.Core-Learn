// =====================================================================
// CityViewModel.cs - ViewModel مربوط به نمایش خلاصه‌ی شهرها
// =====================================================================
// ViewModel یک کلاس ساده است که فقط داده‌های مورد نیاز برای نمایش در View
// را در خود نگه می‌دارد. معمولاً ترکیبی از چند مدل یا فقط بخشی از یک مدل است.
// در اینجا، تعداد شهرها و مجموع جمعیت آن‌ها را نگه می‌دارد.
// =====================================================================

// تعریف namespace مربوط به مدل‌ها
namespace WebApp.Models {

    // تعریف کلاس CityViewModel
    public class CityViewModel {
        // تعداد شهرها (مثلاً 4)
        // int? یعنی می‌تواند null باشد (مثلاً وقتی داده‌ای برای نمایش وجود ندارد)
        public int? Cities { get; set; }

        // مجموع جمعیت شهرها (مثلاً 20187537)
        public int? Population { get; set; }
    }
}
