// =====================================================================
// City.cs - مدل مربوط به شهر
// =====================================================================
// این کلاس ساختار داده‌ای یک شهر را تعریف می‌کند.
// هر شهر سه ویژگی اصلی دارد: نام، کشور و جمعیت.
// از آنجا که این فیلدها اختیاری تعریف شده‌اند (?)، می‌توانند null باشند.
// =====================================================================

// تعریف namespace مربوط به مدل‌ها
namespace WebApp.Models {

    // تعریف کلاس City (شهر)
    // این کلاس یک POCO است که معمولاً به جدولی در پایگاه داده نگاشت می‌شود
    public class City {
        // نام شهر (مثلاً "London")
        // string? یعنی این ویژگی می‌تواند null باشد
        public string? Name { get; set; }

        // نام کشور (مثلاً "UK")
        public string? Country { get; set; }

        // جمعیت شهر (مثلاً 8539000)
        // int? یعنی این ویژگی می‌تواند null باشد
        public int? Population { get; set; }
    }
}
