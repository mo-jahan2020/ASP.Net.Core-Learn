// =============================================================================
// فایل Models/Category.cs — مدل موجودیت دسته‌بندی (Category)
// =============================================================================
// این کلاس یک "Entity" (موجودیت) است که به جدول Categories در دیتابیس نگاشت (Map) می‌شود.
// EF Core با استفاده از Convention (قرارداد)، نام کلاس را به نام جدول و
// خصوصیات را به ستون‌ها نگاشت می‌کند.
// =============================================================================

namespace WebApp.Models {
    // -------------------------------------------------------------------------
    // کلاس Category — موجودیت دسته‌بندی
    // -------------------------------------------------------------------------
    // هر محصول متعلق به یک دسته‌بندی است (رابطه چند به یک: Product -> Category).
    // این کلاس دو خصوصیت دارد: شناسه و نام.
    public class Category {

        // ---------------------------------------------------------------------
        // CategoryId — کلید اصلی (Primary Key)
        // ---------------------------------------------------------------------
        // Convention: EF Core به صورت خودکار خصوصیتی که نامش "Id" باشد یا
        // الگوی "<ClassName>Id" داشته باشد را به عنوان کلید اصلی تشخیص می‌دهد.
        // نوع long (bigint در SQL Server): برای شناسه‌ها معمولاً از long استفاده
        // می‌شود زیرا محدوده بیشتری نسبت به int دارد.
        public long CategoryId { get; set; }

        // ---------------------------------------------------------------------
        // Name — نام دسته‌بندی
        // ---------------------------------------------------------------------
        // = string.Empty: مقدار پیش‌فرض رشته خالی (نه null).
        // این کار هشدارهای Nullable Reference Type را برطرف می‌کند.
        // در دیتابیس به ستون nvarchar(max) تبدیل می‌شود.
        public string Name { get; set; } = string.Empty;

        // ---------------------------------------------------------------------
        // Products — خاصیت ناوبری (Navigation Property)
        // ---------------------------------------------------------------------
        // IEnumerable<Product>?: لیست محصولاتی که در این دسته‌بندی هستند.
        // علامت ?: این لیست می‌تواند null باشد.
        // EF Core با این خاصیت رابطه "یک به چند" (One-to-Many) بین
        // Category و Product را تشخیص می‌دهد.
        // ⚠️ این خاصیت در دیتابیس ستون ندارد! فقط برای ناوبری بین موجودیت‌هاست.
        // با استفاده از آن می‌توانید بدون نوشتن JOIN، محصولات یک دسته را دریافت کنید:
        //   context.Categories.Include(c => c.Products).FirstOrDefault();
        public IEnumerable<Product>? Products { get; set; }
    }
}