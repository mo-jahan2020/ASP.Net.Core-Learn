// =============================================================================
// فایل Models/ProductBindingTarget.cs — کلاس DTO برای دریافت داده محصول
// =============================================================================
// این کلاس یک "DTO" (Data Transfer Object) است که فقط فیلدهایی که کاربر
// اجازه ارسال آن‌ها را دارد، شامل می‌شود.
//
// چرا از DTO استفاده می‌کنیم؟ (الگوی Anti Over-posting)
// ========================================
// اگر کاربر مستقیماً شیء Product را ارسال کند، می‌تواند فیلدهای خطرناکی مثل
// ProductId را دستکاری کند و مثلاً محصول دیگری را بروزرسانی کند!
// با استفاده از DTO، فقط فیلدهای مجاز (Name, Price, CategoryId, SupplierId)
// از بدنه درخواست استخراج می‌شوند و ProductId اصلاً وجود ندارد.
// =============================================================================

using System.ComponentModel.DataAnnotations; // برای ویژگی‌های اعتبارسنجی

namespace WebApp.Models {
    // -------------------------------------------------------------------------
    // کلاس ProductBindingTarget — مدل دریافت داده محصول
    // -------------------------------------------------------------------------
    // این کلاس یک Entity نیست (به جدول دیتابیس نگاشت نمی‌شود).
    // فقط برای دریافت و اعتبارسنجی داده‌های ورودی از کاربر استفاده می‌شود.
    public class ProductBindingTarget {

        // ---------------------------------------------------------------------
        // Name — نام محصول
        // ---------------------------------------------------------------------
        // [Required]: اعتبارسنجی — این فیلد الزامی است.
        // اگر کاربر نام را نفرستد، ASP.NET Core خودکار خطای 400 (Bad Request)
        // با پیام خطای مناسب برمی‌گرداند (به دلیل [ApiController]).
        // = "": مقدار پیش‌فرض رشته خالی (برای جلوگیری از هشدار Null).
        [Required]
        public string Name { get; set; } = "";

        // ---------------------------------------------------------------------
        // Price — قیمت محصول
        // ---------------------------------------------------------------------
        // [Range(1, 1000)]: اعتبارسنجی — قیمت باید بین ۱ تا ۱۰۰۰ باشد.
        // اگر خارج از این محدوده باشد، خطای اعتبارسنجی تولید می‌شود.
        // type decimal: مناسب برای مقادیر مالی (دقت بالا).
        [Range(1, 1000)]
        public decimal Price { get; set; }

        // ---------------------------------------------------------------------
        // CategoryId — شناسه دسته‌بندی
        // ---------------------------------------------------------------------
        // [Range(1, long.MaxValue)]: شناسه باید حداقل ۱ باشد (مثبت).
        // این جلوی ارسال ۰ یا اعداد منفی را می‌گیرد.
        [Range(1, long.MaxValue)]
        public long CategoryId { get; set; }

        // ---------------------------------------------------------------------
        // SupplierId — شناسه تأمین‌کننده
        // ---------------------------------------------------------------------
        // [Range(1, long.MaxValue)]: مشابه CategoryId، باید حداقل ۱ باشد.
        [Range(1, long.MaxValue)]
        public long SupplierId { get; set; }

        // ---------------------------------------------------------------------
        // متد ToProduct() — تبدیل DTO به Entity
        // ---------------------------------------------------------------------
        // این متد یک شیء Product جدید از داده‌های DTO می‌سازد.
        // فقط فیلدهای مجاز کپی می‌شوند (ProductId اصلاً تنظیم نمی‌شود).
        // => : Expression-bodied method — روش کوتاه‌نویسی متدهای تک‌خطی.
        // این متد باعث می‌شود منطق تبدیل در یک مکان متمرکز باشد.
        public Product ToProduct() => new Product() {
            Name = this.Name, Price = this.Price,
            CategoryId = this.CategoryId, SupplierId = this.SupplierId
        };
    }
}