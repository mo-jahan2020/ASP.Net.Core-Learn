// =============================================================================
// فایل Models/Supplier.cs — مدل موجودیت تأمین‌کننده (Supplier)
// =============================================================================
// این کلاس یک موجودیت است که به جدول Suppliers در دیتابیس نگاشت می‌شود.
// هر تأمین‌کننده می‌تواند چند محصول داشته باشد (رابطه یک به چند با Product).
// =============================================================================

namespace WebApp.Models {
    // -------------------------------------------------------------------------
    // کلاس Supplier — موجودیت تأمین‌کننده
    // -------------------------------------------------------------------------
    // این کلاس ساده‌ترین موجودیت برنامه است و فقط سه خصوصیت دارد:
    // شناسه، نام و شهر. روابط بین موجودیت‌ها توسط EF Core از طریق
    // Convention (قراردادهای نام‌گذاری) تشخیص داده می‌شوند.
    public class Supplier {

        // ---------------------------------------------------------------------
        // SupplierId — کلید اصلی (Primary Key)
        // ---------------------------------------------------------------------
        // EF Core این خصوصیت را به عنوان کلید اصلی تشخیص می‌دهد
        // زیرا الگوی "<ClassName>Id" دارد.
        // در دیتابیس از نوع bigint با Identity (خودکار افزایشی) ایجاد می‌شود.
        // Identity: SQL Server به صورت خودکار برای هر رکورد جدید، یک عدد
        // یکتای افزایشی تولید می‌کند (1, 2, 3, ...).
        public long SupplierId { get; set; }

        // ---------------------------------------------------------------------
        // Name — نام تأمین‌کننده
        // ---------------------------------------------------------------------
        // = string.Empty: مقدار پیش‌فرض. در دیتابیس به nvarchar(max) نگاشت می‌شود.
        //IsRequired: EF Core به صورت خودکار رشته‌ها را Required در نظر می‌گیرد.
        public string Name { get; set; } = string.Empty;

        // ---------------------------------------------------------------------
        // City — شهر تأمین‌کننده
        // ---------------------------------------------------------------------
        // = string.Empty: مقدار پیش‌فرض. در دیتابیس به nvarchar(max) نگاشت می‌شود.
        public string City { get; set; } = string.Empty;

        // ---------------------------------------------------------------------
        // Products — خاصیت ناوبری (Navigation Property)
        // ---------------------------------------------------------------------
        // IEnumerable<Product>?: لیست محصولات این تأمین‌کننده.
        // EF Core با این خاصیت رابطه "یک به چند" (One-to-Many) را تشخیص می‌دهد.
        // برای بارگذاری محصولات همراه تأمین‌کننده از Include استفاده کنید:
        //   context.Suppliers.Include(s => s.Products).ToList();
        // بدون Include، این خاصیت null خواهد بود (نه خطا، بلکه null).
        // این رفتار "Lazy Loading" نام دارد (اگر پکیج آن نصب شده باشد)
        // یا "Null" در حالت عادی.
        public IEnumerable<Product>? Products { get; set; }
    }
}