// =============================================================================
// فایل Models/Product.cs — مدل موجودیت محصول (Product)
// =============================================================================
// این کلاس موجودیت اصلی برنامه است. هر نمونه از این کلاس به یک رکورد
// در جدول Products در دیتابیس نگاشت (Map) می‌شود.
// =============================================================================

using System.ComponentModel.DataAnnotations.Schema; // برای ویژگی [Column]
using System.Text.Json.Serialization; // برای ویژگی [JsonIgnore]

namespace WebApp.Models {
    // -------------------------------------------------------------------------
    // کلاس Product — موجودیت محصول
    // -------------------------------------------------------------------------
    // هر محصول متعلق به یک دسته‌بندی (Category) و یک تأمین‌کننده (Supplier) است.
    // روابط: Product → Category (چند به یک) و Product → Supplier (چند به یک)
    public class Product {

        // ---------------------------------------------------------------------
        // ProductId — کلید اصلی (Primary Key)
        // ---------------------------------------------------------------------
        // Convention: EF Core "ProductId" را به عنوان کلید اصلی تشخیص می‌دهد
        // زیرا الگوی "<ClassName>Id" را دارد.
        // نوع long در SQL Server به bigint نگاشت می‌شود و Identity (خودکار) است.
        public long ProductId { get; set; }

        // ---------------------------------------------------------------------
        // Name — نام محصول
        // ---------------------------------------------------------------------
        // = string.Empty: مقدار پیش‌فرض رشته خالی. این کار باعث می‌شود
        // کامپایلر C# هشدار null ندهد (زیرا Nullable فعال است).
        public string Name { get; set; } = string.Empty;

        // ---------------------------------------------------------------------
        // Price — قیمت محصول
        // ---------------------------------------------------------------------
        // [Column(TypeName = "decimal(8, 2)")]: مشخص می‌کند که در دیتابیس
        // این ستون از نوع decimal(8,2) باشد. یعنی حداکثر ۸ رقم کل و ۲ رقم اعشار.
        // این دقت برای قیمت‌ها مناسب است و از مشکلات گرد کردن جلوگیری می‌کند.
        // نکته: بدون این ویژگی، EF Core قیمت را به decimal(18,2) نگاشت می‌کند
        // که فضای بیشتری در دیتابیس اشغال می‌کند.
        // نوع decimal در C# دقت بالایی دارد و برای مقادیر مالی مناسب‌ترین نوع است.
        [Column(TypeName = "decimal(8, 2)")]
        public decimal Price { get; set; }

        // ---------------------------------------------------------------------
        // CategoryId — کلید خارجی (Foreign Key) به جدول Categories
        // ---------------------------------------------------------------------
        // این ستون در دیتابیس به ستون CategoryId جدول Categories ارجاع می‌دهد.
        // EF Core با Convention تشخیص می‌دهد که این یک ForeignKey است
        // زیرا نام آن "<NavigationPropertyName>Id" الگو را دارد
        // و نوع آن با کلید اصلی Category یعنی long یکی است.
        public long CategoryId { get; set; }

        // ---------------------------------------------------------------------
        // Category — خاصیت ناوبری (Navigation Property) به دسته‌بندی
        // ---------------------------------------------------------------------
        // با استفاده از این خاصیت می‌توانید اطلاعات دسته‌بندی محصول را
        // بدون نوشتن JOIN دستی دریافت کنید:
        //   context.Products.Include(p => p.Category).ToList();
        // علامت ?: ممکن است null باشد (Lazy Loading یا عدم بارگذاری).
        // ⚠️ این خصوصیت ستون در دیتابیس ندارد! فقط برای ناوبری است.
        public Category? Category { get; set; }

        // ---------------------------------------------------------------------
        // SupplierId — کلید خارجی (Foreign Key) به جدول Suppliers
        // ---------------------------------------------------------------------
        // این ستون در دیتابیس به ستون SupplierId جدول Suppliers ارجاع می‌دهد.
        // هنگام حذف یک تأمین‌کننده، به دلیل ReferentialAction.Cascade
        // در Migration، تمام محصولات مربوطه نیز حذف خواهند شد.
        public long SupplierId { get; set; }

        // ---------------------------------------------------------------------
        // Supplier — خاصیت ناوبری به تأمین‌کننده
        // ---------------------------------------------------------------------
        // [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]:
        // اگر Supplier بارگذاری نشده (null باشد)، در خروجی JSON گنجانده نمی‌شود.
        // این کار دو مزیت دارد:
        // ۱. حجم پاسخ JSON کمتر می‌شود (بدون فیلدهای null)
        // ۲. از خطاهای ارجاع دوری (Circular Reference) جلوگیری می‌کند
        //    زیرا Supplier هم Products دارد و ممکن است باعث حلقه بینهایت شود.
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
        public Supplier? Supplier { get; set; }
    }
}