// =============================================================================
// فایل TestMiddleware.cs — مثال Middleware سفارشی در ASP.NET Core
// =============================================================================
// Middleware کامپوننتی است که در Pipeline درخواست‌های HTTP قرار می‌گیرد و
// می‌تواند هر درخواست را قبل از رسیدن به کنترلر بررسی و پردازش کند.
// الگوی Middleware بر اساس زنجیره مسئولیت (Chain of Responsibility) کار می‌کند.
// =============================================================================

using WebApp.Models;

namespace WebApp {
    // -------------------------------------------------------------------------
    // کلاس TestMiddleware
    // -------------------------------------------------------------------------
    // این کلاس یک Middleware سفارشی است که بررسی می‌کند آیا مسیر درخواست "/test"
    // هست یا خیر. اگر بله، تعداد رکوردهای هر جدول را برمی‌گرداند.
    // اگر نه، درخواست را به Middleware بعدی در Pipeline منتقل می‌کند.
    public class TestMiddleware {

        // ---------------------------------------------------------------------
        // فیلد nextDelegate
        // ---------------------------------------------------------------------
        // RequestDelegate نماینده‌ای (delegate) است که به Middleware بعدی
        // در Pipeline اشاره می‌کند. با فراخوانی این delegate، درخواست به مرحله
        // بعدی منتقل می‌شود. این مکانیزم "زنجیره Middleware" را تشکیل می‌دهد.
        private RequestDelegate nextDelegate;

        // ---------------------------------------------------------------------
        // Constructor (سازنده)
        // ---------------------------------------------------------------------
        // ASP.NET Core به صورت خودکار پارامتر RequestDelegate را به سازنده تزریق می‌کند.
        // این پارامتر همان Middleware بعدی در Pipeline است.
        public TestMiddleware(RequestDelegate next) {
            nextDelegate = next;
        }

        // ---------------------------------------------------------------------
        // متد Invoke — نقطه اجرای Middleware
        // ---------------------------------------------------------------------
        // این متد برای هر درخواست HTTP فراخوانی می‌شود.
        // پارامتر HttpContext: شامل تمام اطلاعات درخواست (مسیر، هدرها، بدنه و...) و
        //   همچنین امکان ارسال پاسخ (Response) است.
        // پارامتر DataContext: سیستم تزریق وابستگی (DI) به صورت خودکار نمونه
        //   DataContext را تزریق می‌کند تا بتوانیم به دیتابیس دسترسی داشته باشیم.
        public async Task Invoke(HttpContext context, DataContext dataContext) {
            // قبل از اجرای کنترلرها
            // این پیام در کنسول (Terminal) چاپ می‌شود و برای دیباگ مفید است.
            Console.WriteLine("Before Controller Execution");

            // -----------------------------------------------------------------
            // بررسی مسیر درخواست
            // -----------------------------------------------------------------
            // context.Request.Path: مسیر URL درخواست را برمی‌گرداند (مثلاً "/test")
            // اگر مسیر برابر "/test" باشد، Middleware پاسخ را مستقیماً تولید می‌کند
            // و درخواست به کنترلرها نمی‌رسد (شکست زنجیره Middleware).
            if (context.Request.Path == "/test") {
                // WriteAsync: متن را مستقیماً در Response HTTP می‌نویسد.
                // Count(): تعداد رکوردهای هر جدول را از دیتابیس می‌شمارد.
                await context.Response.WriteAsync(
                    $"There are {dataContext.Products.Count()} products\n"); 
                await context.Response.WriteAsync(
                    $"There are {dataContext.Categories.Count()} categories\n");
                await context.Response.WriteAsync(
                    $"There are {dataContext.Suppliers.Count()} suppliers\n");
            } 
            else {
                // -------------------------------------------------------------
                // انتقال درخواست به Middleware بعدی
                // -------------------------------------------------------------
                // اگر مسیر "/test" نباشد، درخواست را به Middleware بعدی در Pipeline
                // منتقل می‌کنیم. این زنجیره تا رسیدن به کنترلر مربوطه ادامه می‌یابد.
                // اگر این خط را فراخوانی نکنید، درخواست هرگز به کنترلر نمی‌رسد
                // و کاربر هیچ پاسخی دریافت نمی‌کند.
                await nextDelegate(context);// درخواست را به کنترلرها منتقل می‌کند
            }
            // بعد از اجرای کنترلرها
            // این پیام پس از تکمیل تمام Middleware ها و کنترلر چاپ می‌شود.
            Console.WriteLine("After Controller Execution");
        }
    }
}